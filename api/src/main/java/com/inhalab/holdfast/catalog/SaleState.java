package com.inhalab.holdfast.catalog;

/**
 * 회차를 목록에서 어떻게 보여줄지. SFR-006의 검수 기준이 "접수종료 노출 방식이
 * 운영정책과 일치"이므로, 판단 근거를 화면 밖으로 꺼내 이름을 붙인다(이슈 #108).
 *
 * <p><b>노출 정책: 감추지 않고 상태를 적는다.</b> 매진·종료된 회차를 목록에서
 * 지우면 "원래 없었는지 이미 끝났는지"를 사용자가 구분할 수 없다. 실제 예약
 * 사이트도 접수종료를 남겨 두고 표시만 바꾼다.
 */
public enum SaleState {

    /** 지금 좌석을 고를 수 있다. */
    ON_SALE,

    /** 예약 오픈 전. 서버도 홀드를 {@code RESERVATION_NOT_OPEN}으로 막는다(REQ-08). */
    NOT_YET_OPEN,

    /** 잔여 좌석 0. */
    SOLD_OUT,

    /** 회차가 닫혔다. */
    CLOSED
}
